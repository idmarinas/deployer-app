/** ¿El cursor está dentro de un comentario, una cadena o el HTML del template? */
function isInIgnoredNode(context: CompletionContext): boolean {
	let node = syntaxTree(context.state).resolveInner(context.pos, -1)
	for (;;) {
		if (IGNORED_NODES.has(node.name)) return true
		const parent = node.parent
		if (!parent) return false
		node = parent
	}
}

/** Fuente de autocompletado de PHP: se registra en `phpLanguage.data` con `withAutocomplete`. */
export const phpCompletionSource: CompletionSource = (
	context: CompletionContext,
): CompletionResult | null => {
	const word = context.matchBefore(WORD)
	// Sin prefijo no se abre sola; con Ctrl+Espacio (`explicit`) sí.
	if (!word || (word.from === word.to && !context.explicit)) return null
	if (isInIgnoredNode(context)) return null

	return { from: word.from, options: phpCompletions, validFor: /^[$\w]*$/ }
}